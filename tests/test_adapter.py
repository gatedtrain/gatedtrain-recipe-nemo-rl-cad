            (d / "adapter_model.safetensors").write_bytes(b"x")
            sc.edit_json(d / "cut.json", lambda c: (c["files"].update({"adapter_model.safetensors": file_sha256(
                d / "adapter_model.safetensors")}), c.update(global_step=20, nemo_rl_step_dir="step_20")))
