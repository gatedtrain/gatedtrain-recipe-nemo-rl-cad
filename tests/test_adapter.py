    def test_make_data_keeps_the_recorded_script_hash(self):
        """make_data.py: a run that reproduces the committed metadata except for its own script hash keeps the recorded
        hash, so the three committed files (and the registered item-set hashes over them) stay byte for byte; any other
        difference does not. Reads this checkout's runtime (the committed files), not REAL."""
        rt = C.REPO / "runtime"
        import importlib.util
        spec = importlib.util.spec_from_file_location("cad_make_data", rt / "make_data.py")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        committed = {rel: (rt / rel).read_bytes() for rel in mod.META_FILES}
        own = mod.sha256_file(rt / "make_data.py")
        fresh = {}
        for rel, b in committed.items():
            m = json.loads(b)
            m["generator"]["script_sha256"] = own
            fresh[rel] = m
        recorded = json.loads(committed["data/data_meta.json"])["generator"]["script_sha256"]
        self.assertEqual(mod.recorded_script_sha256(fresh, committed), recorded)
        for rel, m in fresh.items():
            self.assertEqual(mod.render({**m, "generator": {**m["generator"], "script_sha256": recorded}}),
                             committed[rel])
        changed = json.loads(json.dumps(fresh))
        changed["items-sft/item_set_meta.json"]["items_sha256"] = "sha256:" + "0" * 64
        self.assertIsNone(mod.recorded_script_sha256(changed, committed))
        self.assertIsNone(mod.recorded_script_sha256({k: fresh[k] for k in list(fresh)[:2]}, committed))

