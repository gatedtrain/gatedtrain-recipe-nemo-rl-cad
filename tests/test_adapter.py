def run_executor(*args: str, mirror: "C.CadScenario") -> list[str] | None:
    """The lines runtime/executor/run-executor.sh prints (it never runs docker) for the pinned image and the test
    layout's area and Python tree, their host prefixes replaced by the scenario's mirror; None without the script."""
    import subprocess
    script = C.REPO / "runtime" / "executor" / "run-executor.sh"      # this repository's printer
    if not script.is_file():
        return None
    proc = subprocess.run(["bash", str(script), *args], capture_output=True, text=True, timeout=60,
                          env={"PATH": os.environ.get("PATH", "/usr/bin:/bin"), "GATEDTRAIN_CADEXEC_IMAGE": C.EXECUTOR_IMAGE,
                               "GATEDTRAIN_CADEXEC_AREA": C.AREA6, "GATEDTRAIN_CADEXEC_PYTHON": C.PYTHON_TREE})
    if proc.returncode != 0:
        raise AssertionError(proc.stderr)
    import shlex
    out = []
    for line in proc.stdout.splitlines():
        line = " ".join(shlex.quote(x) for x in shlex.split(line.split("   #")[0]))   # bash %q -> one quoting
        line = line.replace(f"-v {C.PYTHON_TREE}:", f"-v {mirror.python_tree}:")
        line = line.replace(f"-v {C.EXECUTOR}:", f"-v {mirror.runtime}/executor:")
        line = line.replace(f"-v {C.AREA6}:", f"-v {mirror.runtime}:")
        out.append(line)
    return out


def _root_can_read() -> bool:
    return os.geteuid() == 0


class CadCase(unittest.TestCase):
    """One scenario per test that changes it (`fresh`); `self.sc` is shared by the read-only tests of a class."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp(prefix="gatedtrain-ext-cad-"))
        cls.addClassCleanup(shutil.rmtree, cls.tmp, True)
        cls.n = 0
        cls.sc = C.CadScenario(cls.tmp / "shared")

    def fresh(self, **kw) -> C.CadScenario:
        type(self).n += 1
        return C.CadScenario(self.tmp / f"sc-{type(self).n}", **kw)

    def runs(self) -> Path:
        type(self).n += 1
        return self.tmp / f"runs-{type(self).n}"

    # --- in-process checks ---

    def cuts(self, sc: C.CadScenario, stage: str) -> list:
        return adapter().find_cuts(sc.stage_out(stage))[0]

    def log_problems(self, sc: C.CadScenario, stage: str) -> list[str]:
        data = sc.sft_data if stage == "sft" else sc.grpo_data
        return adapter().consumption_problems(sc.stage_out(stage), data, self.cuts(sc, stage))

    def check_problems(self, sc: C.CadScenario, stage: str, launch: dict | None = None) -> list:
        cuts = self.cuts(sc, stage)
        last = cuts[-1][1] if cuts else sc.stage_out(stage) / "cuts" / "checkpoint-6"
        rec = launch if launch is not None else json.loads((sc.root / stage / "launch.json").read_text())
        return adapter().checks(last_cut=last, base=sc.spec_base(stage), launch=rec, base_field="base",
                                stage_out=sc.stage_out(stage), data=sc.sft_data if stage == "sft" else sc.grpo_data,
                                data_field="data", uses=C.SFT_ID if stage == "sft" else C.GRPO_ID)

    def assertProblem(self, msgs, text: str):
        flat = [m if isinstance(m, str) else f"{m.rule} {m.field}: {m.message}" for m in msgs]
        self.assertTrue(any(text in m for m in flat), f"expected a problem containing {text!r}; got {flat}")

    # --- CLI ---

    def passes(self, sc: C.CadScenario, stage: str, **kw) -> Path:
        proc = sc.collect(stage, self.runs(), **kw)
        self.assertIn(proc.returncode, (EXIT_OK, NOT_PASS), describe(proc))
        return parse_run_dir(proc.stdout)

    def refused(self, sc: C.CadScenario, stage: str, rule: str, text: str | None = None, **kw):
        runs = self.runs()
        proc = sc.collect(stage, runs, **kw)
        self.assertEqual(proc.returncode, EXIT_REFUSED, describe(proc))
        self.assertNotIn("Traceback", proc.stderr)
        errs = parse_errors(proc.stderr)
        hits = [e for e in errs if e["rule"] == rule and (text is None or text in e["message"])]
        self.assertTrue(hits, f"expected error[{rule}] {text!r}; got {errs}\n{describe(proc)}")
        self.assertFalse(runs.exists() and any(runs.iterdir()), "a refusal writes no run directory")
        return hits

    def unreadable(self, p: Path) -> None:
        if _root_can_read():
            self.skipTest("running as root: chmod 0 does not make a file unreadable")
        p.chmod(0)
        self.addCleanup(p.chmod, 0o644)


