        self.assertEqual(incomplete, [])

        def broken(name: str, fn) -> str:
            d = cuts / name
            shutil.copytree(cuts / "checkpoint-6", d)
            fn(d)
            step = int(name.split("-")[1])
            return adapter().cut_problem(d, step)

        self.assertIn("cut.json", broken("checkpoint-10", lambda d: (d / "cut.json").unlink()))
        self.assertIn("not list", broken("checkpoint-11", lambda d: (d / "optimizer.pt").write_text("x")))
        self.assertIn("SHA-256", broken("checkpoint-12", lambda d: (d / "config.json").write_text("{}")))

        def drop_info(d):
            (d / "training_info.json").unlink()
            sc.edit_json(d / "cut.json", lambda c: c["files"].pop("training_info.json"))
        self.assertIn("training_info.json", broken("checkpoint-13", drop_info))
        self.assertIn("global_step", broken("checkpoint-14", lambda d: None))       # cut.json says 6
        self.assertIn("deployable", broken("checkpoint-15", lambda d: (
            sc.edit_json(d / "cut.json", lambda c: c.update(deployable=["model.safetensors"])),
            sc.edit_json(d / "cut.json", lambda c: c.update(global_step=15, nemo_rl_step_dir="step_15")))))
        self.assertIn("nemo_rl_step_dir", broken("checkpoint-16", lambda d: sc.edit_json(
            d / "cut.json", lambda c: c.update(global_step=16, nemo_rl_step_dir="step_6"))))
        self.assertIn("global_step", broken("checkpoint-17", lambda d: sc.edit_json(
            d / "cut.json", lambda c: c.update(global_step=True))))
        self.assertIn("stage", broken("checkpoint-18", lambda d: sc.edit_json(
            d / "cut.json", lambda c: c.update(global_step=18, nemo_rl_step_dir="step_18", stage="dpo"))))
        self.assertIn("examples_consumed", broken("checkpoint-19", lambda d: sc.edit_json(
            d / "cut.json", lambda c: c.update(global_step=19, nemo_rl_step_dir="step_19", examples_consumed=False))))
        # an unknown file that cut.json lists (an LoRA adapter, say) is not a component of this layout
