class TestExecRecord(CadCase):
    """EXT-199: exec_meta.json beside the arm (the execution step's record) against the scoring record."""

    def problems(self, sc: C.CadScenario) -> list[str]:
        from gatedtrain.ext.arm import read_lines
        arm = sc.arms["sft"][1] / "arm-iou"
        recs, _ = read_lines(arm, seeds=[11], score_range=(0, 1),
                             error_classes=("executor_error", "scorer_error", "missing_output"))
        return adapter().arm_problems(arm, recs, sc.items["sft"], items_dir=sc.items_dir["sft"], model_dir=sc.sft_cut)

    def edit_exec(self, sc: C.CadScenario, fn, *, reseal: bool = True) -> None:
        root = sc.arms["sft"][1]
        doc = json.loads((root / "exec_meta.json").read_text())
        fn(doc)
        (root / "exec_meta.json").write_text(json.dumps(doc, sort_keys=True, indent=1) + "\n")
        if reseal:
            sc.edit_json(root / "env-runtime.json",
                         lambda e: e.update(exec_meta_sha256=file_sha256(root / "exec_meta.json")))

    def test_clean(self):
        self.assertEqual(self.problems(self.sc), [])

    def test_exec_record_missing(self):
        sc = self.fresh()
        (sc.arms["sft"][1] / "exec_meta.json").unlink()
        self.assertProblem(self.problems(sc), "exec_meta.json")

    def test_exec_record_not_the_one_scored(self):
        sc = self.fresh()
        self.edit_exec(sc, lambda d: d.update(ids=d["ids"] + ["x__s11"]), reseal=False)
        self.assertProblem(self.problems(sc), "exec_meta_sha256")

    def test_exec_record_fields(self):
        cases = [
            (lambda d: d["code_sha256"].update({"cad_sandbox.py": "sha256:" + "1" * 64}), "executor code"),
            (lambda d: d.update(gen_meta_sha256="sha256:" + "2" * 64), "another generation"),
            (lambda d: d.update(limits=dict(d["limits"], cpu_s=100)), "limits"),
            (lambda d: d.update(schema="other"), "schema"),
            (lambda d: d["ids"].pop(0), "no execution"),
            (lambda d: d["files"].pop(f"programs/{d['ids'][1]}/result.json"), "result.json"),
            (lambda d: d["files"].update({f"programs/{d['ids'][0]}/mesh.stl": "sha256:" + "3" * 64}), "mesh.stl"),
        ]
        for fn, text in cases:
            with self.subTest(text=text):
                sc = self.fresh()
                self.edit_exec(sc, fn)
                self.assertProblem(self.problems(sc), text)

    def test_scoring_record_executor_code(self):
        sc = self.fresh()
        sc.edit_json(sc.arms["sft"][1] / "env-runtime.json",
                     lambda e: e["code_sha256"].update({"cad_protocol.py": "sha256:" + "4" * 64}))
        self.assertProblem(self.problems(sc), "executor code")

    def test_refused_at_collect(self):
        sc = self.fresh()
        self.edit_exec(sc, lambda d: d["code_sha256"].update({"cad_sandbox.py": "sha256:" + "1" * 64}))
        self.refused(sc, "sft", "EXT-ARM", "executor code")


